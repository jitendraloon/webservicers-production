function buildInitialProducts(): AdminProduct[] {
  const catMap: Record<string, { id: string; name: string }> = {
    Presence: { id: "cat_presence", name: "Presence & Web" },
    Promote: { id: "cat_promote", name: "Promote & Paid Ads" },
    Analytics: { id: "cat_analytics", name: "Analytics & Intelligence" },
  };

  return SERVICES.map((svc, idx) => {
    const cat = catMap[svc.category] ?? catMap.Presence;
    return {
      id: `prod_${svc.slug}`,
      slug: svc.slug,
      name: svc.name,
      shortName: svc.shortName,
      categoryId: cat.id,
      categoryName: cat.name,
      type: svc.slug === "social-media-marketing" ? "smm" : "service",
      status: "ACTIVE",
      tagline: svc.tagline,
      description: svc.description,
      basePriceCents: svc.priceUsd * 100,
      tiers: svc.tiers.map((t, tIdx) => ({
        id: `tier_${svc.slug}_${t.name.toLowerCase()}`,
        name: t.name,
        priceCents: t.priceUsd * 100,
        annualDiscountPct: 20,
        deliveryDays: tIdx === 0 ? 5 : tIdx === 1 ? 10 : 14,
        features: t.features,
      })),
      addonIds: idx % 2 === 0 ? ["addon_priority_sla", "addon_dedicated_am"] : ["addon_priority_sla"],
      requirementIds: ["req_domain", "req_goal", "req_brand_kit"],
      activeSubscriptions: 12 + ((idx * 7) % 38),
    };
  });
}

