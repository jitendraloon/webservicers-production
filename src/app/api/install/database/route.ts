import { NextResponse } from "next/server";
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { execSync } from "node:child_process";
import { isInstallLocked } from "@/server/install/guard";

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

export async function POST(request: Request) {
  if (isInstallLocked()) {
    return NextResponse.json(
      { error: "Installer is locked. Delete storage/.install-locked via SSH/File Manager to re-run." },
      { status: 403 }
    );
  }

  let body: {
    dbType?: string;
    host?: string;
    port?: string;
    database?: string;
    username?: string;
    password?: string;
    appUrl?: string;
  };

  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: "Invalid JSON payload" }, { status: 400 });
  }

  const host = (body.host || "localhost").trim();
  const port = (body.port || "3306").trim();
  const database = (body.database || "").trim();
  const username = (body.username || "").trim();
  const password = body.password ?? "";
  const proto = request.headers.get("x-forwarded-proto") || "https";
  const reqHost = request.headers.get("x-forwarded-host") || request.headers.get("host") || "localhost:3000";
  const defaultAppUrl = `${proto}://${reqHost}`;
  const appUrl = (body.appUrl || defaultAppUrl).trim().replace(/\/$/, "");

  if (!database || !username) {
    return NextResponse.json(
      { error: "Database name and database username are required." },
      { status: 400 }
    );
  }

  // 1. Verify TCP connectivity to MariaDB/MySQL host:port first
  const net = await import("node:net");
  const tcpCheck = await new Promise<{ ok: boolean; error?: string }>((resolve) => {
    const socket = net.createConnection({ host, port: Number(port) }, () => {
      socket.end();
      resolve({ ok: true });
    });
    socket.setTimeout(6000);
    socket.on("timeout", () => {
      socket.destroy();
      resolve({
        ok: false,
        error: `Connection timed out connecting to database host ${host}:${port}. Verify database host and port.`,
      });
    });
    socket.on("error", (err) => {
      resolve({
        ok: false,
        error: `Could not reach database host at ${host}:${port}: ${err.message}`,
      });
    });
  });

  if (!tcpCheck.ok) {
    return NextResponse.json(
      {
        error: "Could not connect to MariaDB/MySQL server.",
        detail: tcpCheck.error,
      },
      { status: 400 }
    );
  }

  const encodedUser = encodeURIComponent(username);
  const encodedPass = encodeURIComponent(password);
  const databaseUrl = `mysql://${encodedUser}:${encodedPass}@${host}:${port}/${database}`;

  const rootDir = process.cwd();

  // 2. Configure prisma/schema.prisma for MariaDB/MySQL
  try {
    const schemaMysqlPath = path.join(rootDir, "prisma", "schema.mysql.prisma");
    const schemaPath = path.join(rootDir, "prisma", "schema.prisma");
    if (fs.existsSync(schemaMysqlPath)) {
      fs.copyFileSync(schemaMysqlPath, schemaPath);
    } else if (fs.existsSync(schemaPath)) {
      let schemaText = fs.readFileSync(schemaPath, "utf8");
      if (schemaText.includes('provider = "sqlite"')) {
        schemaText = schemaText.replace(/provider\s*=\s*"sqlite"/, 'provider = "mysql"');
        fs.writeFileSync(schemaPath, schemaText, "utf8");
      }
    }
  } catch (schemaErr) {
    console.error("[install] Warning syncing MySQL schema:", schemaErr);
  }

  // 3. Generate secure application secrets and write .env & .env.local
  const sessionSecret = crypto.randomBytes(32).toString("hex");
  const encryptionKey = crypto.randomBytes(32).toString("hex");
  const cronSecret = crypto.randomBytes(24).toString("hex");

  const envContent = [
    `# WebServicers Production Environment (Generated by /install)`,
    `DATABASE_URL="${databaseUrl}"`,
    `SESSION_SECRET="${sessionSecret}"`,
    `ENCRYPTION_KEY="${encryptionKey}"`,
    `CRON_SECRET="${cronSecret}"`,
    `NEXT_PUBLIC_APP_URL="${appUrl}"`,
    `NEXT_PUBLIC_APP_NAME="WebServicers"`,
    `NODE_ENV="production"`,
    "",
  ].join("\n");

  fs.writeFileSync(path.join(rootDir, ".env"), envContent, "utf8");
  fs.writeFileSync(path.join(rootDir, ".env.local"), envContent, "utf8");

  // Immediately update process.env in the active Node.js server process
  process.env.DATABASE_URL = databaseUrl;
  process.env.SESSION_SECRET = sessionSecret;
  process.env.ENCRYPTION_KEY = encryptionKey;
  process.env.CRON_SECRET = cronSecret;

  // Ensure storage folder exists
  try {
    fs.mkdirSync(path.join(rootDir, "storage"), { recursive: true });
  } catch {}

  // 4. Ensure binary execute permissions on Linux/cPanel systems
  if (process.platform !== "win32") {
    try {
      execSync("chmod -R +x node_modules/.bin node_modules/@prisma node_modules/prisma 2>/dev/null || true", {
        cwd: rootDir,
        stdio: "ignore",
      });
    } catch {}
  }

  // 5. Push Prisma schema to MariaDB/MySQL (validates credentials & creates tables)
  const prismaJs = path.join(rootDir, "node_modules", "prisma", "build", "index.js");
  const prismaBin = path.join(rootDir, "node_modules", ".bin", "prisma");

  if (process.platform !== "win32" && fs.existsSync(prismaBin)) {
    try {
      fs.chmodSync(prismaBin, 0o755);
    } catch {}
  }

  const envPath = `${path.dirname(process.execPath)}:${process.env.PATH || ""}`;
  const pushCommand = fs.existsSync(prismaJs)
    ? `"${process.execPath}" "${prismaJs}" db push --accept-data-loss`
    : `npx prisma db push --accept-data-loss`;

  try {
    execSync(pushCommand, {
      cwd: rootDir,
      env: {
        ...process.env,
        PATH: envPath,
        DATABASE_URL: databaseUrl,
      },
      stdio: "pipe",
    });
  } catch (err: any) {
    const stdout = err?.stdout ? String(err.stdout) : "";
    const stderr = err?.stderr ? String(err.stderr) : "";
    const detail = [err?.message, stderr, stdout].filter(Boolean).join("\n");
    return NextResponse.json(
      {
        error: "Could not connect to MariaDB/MySQL with the provided credentials.",
        detail: detail || (err instanceof Error ? err.message : String(err)),
      },
      { status: 400 }
    );
  }

  // 6. Regenerate Prisma Client with MySQL engine
  try {
    const genCommand = fs.existsSync(prismaJs)
      ? `"${process.execPath}" "${prismaJs}" generate`
      : `npx prisma generate`;

    execSync(genCommand, {
      cwd: rootDir,
      env: {
        ...process.env,
        PATH: envPath,
        DATABASE_URL: databaseUrl,
      },
      stdio: "pipe",
    });
  } catch (genErr) {
    console.warn("[install] Warning running prisma generate:", genErr);
  }

  // 7. Seed essential roles, currencies, and payment gateways with fresh MySQL client
  let seedPrisma: any = null;
  try {
    Object.keys(require.cache).forEach((k) => {
      if (k.includes("@prisma/client") || k.includes(".prisma")) {
        delete require.cache[k];
      }
    });

    const { PrismaClient: FreshPrismaClient } = require("@prisma/client");
    seedPrisma = new FreshPrismaClient({
      datasources: { db: { url: databaseUrl } },
    });

    const roles = [
      { name: "Super Admin", description: "Full system access", permissions: [{ module: "*", action: "*" }] },
      { name: "Support Agent", description: "Support & tickets", permissions: [{ module: "tickets", action: "*" }] },
      { name: "SEO Specialist", description: "SEO workspace & reports", permissions: [{ module: "seo", action: "*" }] },
    ];
    for (const r of roles) {
      await seedPrisma.role.upsert({
        where: { name: r.name },
        update: {},
        create: r,
      });
    }

    const currencies = [
      { code: "USD", symbol: "$", name: "US Dollar", exchangeRateToUsd: 1 },
      { code: "EUR", symbol: "€", name: "Euro", exchangeRateToUsd: 0.92 },
      { code: "GBP", symbol: "£", name: "British Pound", exchangeRateToUsd: 0.79 },
      { code: "INR", symbol: "₹", name: "Indian Rupee", exchangeRateToUsd: 84.0 },
      { code: "CAD", symbol: "C$", name: "Canadian Dollar", exchangeRateToUsd: 1.38 },
      { code: "AUD", symbol: "A$", name: "Australian Dollar", exchangeRateToUsd: 1.52 },
    ];
    for (const c of currencies) {
      await seedPrisma.currency.upsert({
        where: { code: c.code },
        update: {},
        create: c,
      });
    }

    const gateways = [
      { slug: "wallet", name: "Website Wallet", isBuiltin: true, enabled: true, sortOrder: 1 },
      { slug: "stripe", name: "Stripe", isBuiltin: true, enabled: false, sortOrder: 2 },
      { slug: "paypal", name: "PayPal", isBuiltin: true, enabled: false, sortOrder: 3 },
      { slug: "razorpay", name: "Razorpay", isBuiltin: true, enabled: false, sortOrder: 4 },
      { slug: "payu", name: "PayU", isBuiltin: true, enabled: false, sortOrder: 5 },
      { slug: "cashfree", name: "CashFree", isBuiltin: true, enabled: false, sortOrder: 6 },
      { slug: "coinpayments", name: "CoinPayments", isBuiltin: true, enabled: false, sortOrder: 7 },
      { slug: "bank_manual", name: "Bank Transfer (Manual)", isBuiltin: true, enabled: true, sortOrder: 8 },
    ];
    for (const g of gateways) {
      await seedPrisma.paymentGateway.upsert({
        where: { slug: g.slug },
        update: {},
        create: g,
      });
    }
  } catch (seedErr) {
    console.warn("[install] Seed warning (tables were created successfully):", seedErr);
  } finally {
    if (seedPrisma) {
      await seedPrisma.$disconnect().catch(() => {});
    }
  }

  // 8. Signal Passenger restart file
  try {
    const tmpDir = path.join(rootDir, "tmp");
    fs.mkdirSync(tmpDir, { recursive: true });
    fs.writeFileSync(path.join(tmpDir, "restart.txt"), String(Date.now()), "utf8");
  } catch {}

  return NextResponse.json({
    ok: true,
    message: "MariaDB connected, .env configured, tables created, and base data seeded.",
    cronSecret,
  });
}
